// نظام القوالب — كل قالب يعرّف طبقة بصرية كاملة (توكنات + إطار + كثافة زخرفة)
// فوق نفس الكتل الدلالية الـ١٤، فلا يتكرر منطق العرض.

import type { ComponentType } from "react"

export interface TemplateTokens {
  /** خلفية الصفحة */
  bg: string
  /** لون الحبر الأساسي (النصوص) */
  ink: string
  /** لون التمييز (الزخارف، الخطوط، الإطار) */
  accent: string
  /** لون خافت للنصوص الثانوية */
  muted: string
  nameFont: string
  bodyFont: string
  calligraphyFont: string
}

export interface TemplateDefinition {
  id: string
  name: string
  category: "تقليدي" | "حديث" | "ملكي"
  description: string
  tokens: TemplateTokens
  /** طبقة SVG/CSS للإطار — يُرسم خلف المحتوى بكامل الصفحة */
  Frame: ComponentType<{ className?: string }>
  /** رمز الفاصل الزخرفي بين الكتل، فارغ = خط بسيط فقط */
  divider: string
  /** هل يظهر فوتر المطبعة (خط أفقي + سطر صغير)؟ */
  showPrintFooter: boolean
  /** تخطيط اسم الفقيد: وسط بسيط / داخل شارة / تحت مخطوطة مهيمنة */
  nameLayout: "plain" | "badge" | "calligraphy-dominant"
  /**
   * تخطيط كتلة الأقارب: افتراضياً "centered-wrap" (سطر ملتفّ في المنتصف، كل الفئات
   * تتدفّق معاً). "justified-lines" (طرابلس وشمال لبنان حصراً) يعرض كل فئة على سطر
   * منفصل بعرض الصفحة كاملاً — بلا توسيط — بتسمية مطوَّلة بحرف التطويل العربي (ـ)
   * قبل النقطتين، مطابقةً لتنضيد الصحف الورقية التقليدية.
   */
  relativesLayout?: "centered-wrap" | "justified-lines"
  /** حجم اسم الفقيد بوحدة em — افتراضياً ٢.٥ لكل القوالب إن غاب هذا الحقل. قابل
   * للتجاوز لكل قالب لإبراز الاسم كأكبر عنصر في الصفحة (طرابلس وشمال لبنان: ٤). */
  nameSizeEm?: number
  /**
   * موضع المخطوطة القرآنية العلوية: "center" (افتراضي، وسط الصفحة بحجمها الطبيعي،
   * فوق الجهة الناعية) أو "corner" (طرابلس وشمال لبنان حصراً) — مصغّرة في الزاوية
   * العلوية اليسرى، بجانب الجهة الناعية في صفّ واحد بدل التتابع الرأسي.
   */
  quranPlacement?: "center" | "corner"
  /**
   * نطاق سطر "العائلات" أسفل الصفحة: "all" (افتراضي، مُشتق من عائلات كل الأقارب
   * المُدخَلين وأصهارهم) أو "parents-only" (طرابلس وشمال لبنان حصراً) — عائلة الأب
   * (لقب الفقيد نفسه) وعائلة الأم فقط. راجع parentFamiliesLine في render.ts.
   */
  familiesLineScope?: "all" | "parents-only"
  /**
   * إبراز اسم مكان الصلاة (المسجد) كسطر عريض مستقل بعد جملة الصلاة، بدل دمجه داخل
   * الجملة نفسها كما في بقية القوالب (طرابلس وشمال لبنان حصراً).
   */
  emphasizePrayerLocation?: boolean
  /**
   * حوّل مخطوطات SVG اليدوية (حبر أسود/داكن أصلاً) إلى الأبيض عبر فلتر CSS —
   * ضروري للقوالب ذات الخلفية الداكنة (الليلي الفخم) وإلا تختفي المخطوطة على الأسود.
   */
  calligraphyInvert?: boolean
  /**
   * إخفاء مؤقّت من كل واجهات اختيار القالب (المحرر + معرض الصفحة الرئيسية) بلا حذف
   * تعريفه — يبقى القالب صالحاً تماماً عبر getTemplate(id) لأي نعوة محفوظة سلفاً
   * تستعمله فعلياً. لإعادة إظهاره لاحقاً: احذف هذا الحقل أو اجعله false.
   */
  hidden?: boolean
}
